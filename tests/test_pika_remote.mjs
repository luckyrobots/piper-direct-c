import assert from 'node:assert/strict';
import { webcrypto } from 'node:crypto';
import { RemotePikaPort } from '../web/pika_remote.mjs';
import { packet } from '../web/pika.mjs';
globalThis.crypto ??= webcrypto;
let clear = false, position = .5756;
const calls = [];
const fetcher = async function (url, options = {}) {
  assert.equal(this, undefined, 'fetch must not receive the port as its receiver');
  const body = options.body ? JSON.parse(options.body) : null;
  calls.push({ url, ...body });
  if (url === '/api/pika/state') return { ok: true, json: async () => ({ connected: true, fresh: true, telemetry: { motor: { Position: position }, motorstatus: { Status: '0x00' } } }) };
  assert.equal(options.headers['X-Piper-Token'], 'fixture-token');
  assert.match(body.owner, /^[0-9a-f-]{36}$/);
  if (url.endsWith('/enable') && !body.clear) return { ok: false, json: async () => ({ error: 'Finger-clear confirmation required' }) };
  if (url.endsWith('/position')) position = body.value;
  return { ok: true, json: async () => ({ ok: true }) };
};
const port = await RemotePikaPort.connect({ token: () => 'fixture-token', clear: () => clear, fetcher });
assert.equal(calls[0].url, '/api/pika/connect');
assert.ok(!calls.some(c => /enable|position|disable/.test(c.url)), 'Connect must not send motor commands');
const reader = port.readable.getReader();
assert.equal(JSON.parse(new TextDecoder().decode((await reader.read()).value)).motor.Position, .5756);
const writer = port.writable.getWriter();
await assert.rejects(writer.write(packet(11)), /Finger-clear/);
clear = true;
await writer.write(packet(11));
await writer.write(packet(22, .6));
assert.ok(Math.abs(position - .6) < 1e-6);
await assert.rejects(writer.write(Uint8Array.of(1, 2)), /Invalid Pika packet/);
await writer.write(packet(10));
writer.releaseLock();
await reader.cancel(); reader.releaseLock(); await port.close();
assert.equal(calls.at(-1).url, '/api/pika/disconnect');
console.log('Pika backend relay passed: read-only connect, ownership/token, rejected enable recovery, binary translation, stop and disconnect.');
